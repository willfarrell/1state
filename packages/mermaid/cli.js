// Render machine definitions as a markdown document of mermaid diagrams.
//
//   1state-mermaid examples/onboard.js > examples/ONBOARD.md
//   1state-mermaid --check examples/ONBOARD.md examples/onboard.js
//
// --check is the reason this is a command and not just a library call: it
// re-renders and compares, so a committed diagram that no longer matches its
// machine fails CI instead of quietly going stale.
//
// ponytail: the module loader below is fifteen lines that `1state-validate` also
// has. Sharing them would cost a package or push filesystem code into core —
// both worse than two copies.

import { readFile } from "node:fs/promises";
import { basename, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { parseArgs } from "node:util";
import render from "./index.js";

const USAGE = `Usage: 1state-mermaid [--title <text>] [--check <file>] <file...>

  <file>          .js module exporting machine definitions, or a .json machine
  --title <text>  document heading
  --check <file>  compare against <file> instead of writing; non-zero on drift
  -h, --help      this
`;

const { values, positionals } = parseArgs({
	options: {
		title: { type: "string" },
		check: { type: "string" },
		help: { type: "boolean", short: "h" },
	},
	allowPositionals: true,
});

if (values.help || !positionals.length) {
	process.stdout.write(USAGE);
	process.exit(values.help ? 0 : 1);
}

// A JSON file holds one machine and borrows the file's name. Anything with
// states or an initial is a machine; a `scripts` export sitting beside them is
// not. Export order is definition order, which reads bottom-up — you meet a
// section before the flow that nests it.
const machinesIn = async (file) => {
	if (file.endsWith(".json"))
		return [[basename(file), JSON.parse(await readFile(file, "utf8"))]];
	const module = await import(pathToFileURL(resolve(file)).href);
	return Object.entries(module).filter(
		([, value]) =>
			value &&
			typeof value === "object" &&
			("states" in value || "initial" in value),
	);
};

const sections = [];
for (const file of positionals)
	for (const [name, definition] of await machinesIn(file))
		sections.push(`## \`${name}\`\n\n${render(definition, { title: name })}\n`);

const document = `# ${values.title ?? "State machines"}

Generated by \`1state-mermaid\` — edit the machine, not this file. Guards print as
written, so a diagram shows every branch, including the ones current answers
would skip.

${sections.join("\n")}`;

if (!values.check) {
	process.stdout.write(document);
	process.exit(0);
}

const current = await readFile(values.check, "utf8").catch(() => null);
if (current === document) process.exit(0);
process.stderr.write(
	`${values.check} is out of date — re-run without --check to regenerate\n`,
);
process.exit(1);
